GRANT SELECT,INSERT,UPDATE,DELETE ON SCHEMA::audit TO [FVN_REGISTER_APP];
GRANT SELECT,INSERT,UPDATE,DELETE ON SCHEMA::config TO [FVN_REGISTER_APP];
