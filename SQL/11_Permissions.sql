GRANT SELECT,INSERT,UPDATE,DELETE ON SCHEMA::leave TO [FVN_REGISTER_APP];
GRANT SELECT,INSERT,UPDATE,DELETE ON SCHEMA::ot TO [FVN_REGISTER_APP];
GRANT SELECT,INSERT,UPDATE,DELETE ON SCHEMA::trip TO [FVN_REGISTER_APP];
GRANT SELECT,INSERT,UPDATE,DELETE ON SCHEMA::equipment TO [FVN_REGISTER_APP];
